  function replaceFlexible(value,from,to){
    return String(value||'').replace(flexiblePattern(from),to);
  }

  function translateHtml(original,item){
    const template=document.createElement('template');
    template.innerHTML=String(original||'');
    const walker=document.createTreeWalker(template.content,NodeFilter.SHOW_TEXT);
    let node;
    while((node=walker.nextNode())){
      let value=node.nodeValue||'';
      value=replaceFlexible(value,item.skDescription,item.csDescription);
      for(const [sk,cs] of COMMON_TEXT_PAIRS)value=replaceFlexible(value,sk,cs);
      node.nodeValue=value;
    }
    return template.innerHTML;
  }

